    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
 try {
            String marca = txtMarca.getText();
            double gasolina = Double.parseDouble(txtGasolina.getText());
            double capacidad = Double.parseDouble(txtCapacidad.getText());
            camioneta = new Camioneta(marca, gasolina, capacidad);
            lblResultado.setText("Camioneta creada");
        } catch (NumberFormatException e) {
            lblResultado.setText("Escribe números válidos");
        } catch (IllegalArgumentException e) {
            lblResultado.setText(e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnCrearActionPerformed

    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        if (camioneta == null) {
            lblResultado.setText("Primero crea la camioneta");
            return;
        }
        try {
            double litros = Double.parseDouble(txtCantidad.getText());
            if (camioneta.cargarGasolina(litros)) {
                lblResultado.setText("Gasolina: " + camioneta.getGasolina() + " litros");
            } else {
                lblResultado.setText("Cantidad inválida");
            }
        } catch (NumberFormatException e) {
            lblResultado.setText("Cantidad inválida");
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnViajarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViajarActionPerformed
        if (camioneta == null) {
            lblResultado.setText("Primero crea la camioneta");
            return;
        }
        try {
            double km = Double.parseDouble(txtCantidad.getText());
            if (camioneta.viajar(km)) {
                String aviso = "";
                if (camioneta.necesitaGasolina()) {
                    aviso = " - ¡poca gasolina!";
                }
                lblResultado.setText("Kilometraje: " + camioneta.getKilometraje()
                        + " km, gasolina: " + camioneta.getGasolina() + aviso);
            } else {
                lblResultado.setText("No alcanza la gasolina");
            }
        } catch (NumberFormatException e) {
            lblResultado.setText("Cantidad inválida");
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnViajarActionPerformed

    private void btnAlcanceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlcanceActionPerformed
        if (camioneta == null) {
            lblResultado.setText("Primero crea la camioneta");
            return;
        }
        int litros = (int) camioneta.getGasolina();
        int km = camioneta.kmPosibles(litros);
        lblResultado.setText("Con " + litros + " litros puedes recorrer " + km + " km");        // TODO add your handling code here:
    }//GEN-LAST:event_btnAlcanceActionPerformed

    private void btnCargaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargaActionPerformed
        if (camioneta == null) {
            lblResultado.setText("Primero crea la camioneta");
            return;
        }
        try {
            double peso = Double.parseDouble(txtPeso.getText());
            if (camioneta.puedeCargar(peso)) {
                lblResultado.setText("Sí aguanta esa carga");
            } else {
                lblResultado.setText("Demasiado peso");
            }
        } catch (NumberFormatException e) {
            lblResultado.setText("Peso inválido");
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnCargaActionPerformed

